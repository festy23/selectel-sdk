#!/usr/bin/env python3
"""Generate the explicitly source-confirmed metrics namespace/string contracts offline."""
import json
import subprocess
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
evidence = json.loads((ROOT / 'catalog/evidence/metrics-read-sources.json').read_text())
p = ROOT / 'catalog/sources/prometheus-metrics.json'
source = json.loads(p.read_text())
assert '[ <unix_time>, "<string_value>" ]' in source['x-upstream-reference']['document']
directory = next(d['document'] for d in evidence['documents'] if d['uri'].endswith('/metrics-references.md'))
for namespace in evidence['namespaces']:
    assert '`' + namespace + '`' in directory
source['x-selectel-read-subset'] = {
    'namespaces': evidence['namespaces'], 'disposition': evidence['disposition'],
    'evidence': [{'uri': d['uri'], 'sha256': d['sha256']} for d in evidence['documents']],
}
p.write_text(json.dumps(source, indent=2) + '\n')
cases = ', '.join(json.dumps(n) for n in evidence['namespaces'])
text = '''// Code generated by internal/metricsgen/generate.py; DO NOT EDIT.
// Sources: pinned Selectel namespace directory and Prometheus string-result contract.
package metrics

import "github.com/festy23/selectel-sdk/types"

// StringSample preserves arbitrary provider text at an explicit Reveal boundary.
type StringSample struct {
 Timestamp types.Number `json:"timestamp"`
 Value types.ProtectedValue `json:"value"`
}

func validNamespace(value string) bool {
 switch value {
 case ''' + cases + ''': return true
 default: return false
 }
}
'''
(ROOT / 'metrics/read_types_generated.go').write_text(text)
subprocess.run(['gofmt', '-w', str(ROOT / 'metrics/read_types_generated.go')], check=True)
