#!/usr/bin/env python3
"""Generate confirmed Logs write inventory and response DTOs offline from pinned sources."""
import copy
import json
import subprocess
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
source = ROOT / 'catalog/sources/cloudwatch-logs.json'
s = json.loads(source.read_text())
evidence = json.loads((ROOT / 'catalog/evidence/logs-write-sources.json').read_text())
model = copy.deepcopy(s['x-upstream-model'])
additions = evidence['response_additions']
model['shapes'].update(additions['shapes'])
for name, members in additions['members'].items():
    model['shapes'][name]['members'].update(members)
s['x-write-response-additions'] = additions
for action, fields in evidence['operations'].items():
    op = model['operations'][action]
    shape = model['shapes'][op['input']['shape']]
    supported = {name: shape['members'][name] for name in fields}
    s['paths']['/' + action] = {'post': {
        'x-effect': 'mutation', 'x-operation-locator': 'CloudWatch ' + action,
        'x-source-uri': 'https://docs.selectel.ru/logs/manage/' + ('delete-logs/' if action.startswith('Delete') else 'add-logs/'),
        'x-wire-path': '/', 'x-amz-target': 'Logs_20140328.' + action,
        'x-selectel-evidence': '../evidence/logs-write-sources.json',
        'request_shape': {'type': 'structure', 'required': fields, 'members': supported},
        'responses': {'200': op.get('output', {'type': 'structure', 'members': {}})},
        'errors': op.get('errors', []),
        'x-unsupported-aws-fields': sorted(set(shape['members']) - set(fields)),
    }}
source.write_text(json.dumps(s, indent=2) + '\n')
roots = ['InputLogEvent', 'PutLogEventsResponse', 'RejectedLogEventsInfo', 'RejectedEntityInfo']
lines = ['// Code generated by internal/logsgen/generate.py; DO NOT EDIT.', '// Source: catalog/sources/cloudwatch-logs.json x-upstream-model shapes plus pinned x-write-response-additions.', 'package logs', '', 'import "github.com/festy23/selectel-sdk/types"', '']
for name in roots:
    shape = model['shapes'][name]
    lines.append('type ' + name + ' struct {')
    for key, item in shape['members'].items():
        target = model['shapes'][item['shape']]
        if item['shape'] in roots:
            typ = item['shape']
        elif key in ['message', 'nextSequenceToken', 'errorType']:
            typ = 'types.ProtectedValue'
        elif target['type'] in ['integer', 'long']:
            typ = 'types.Integer'
        else:
            raise ValueError((key, item))
        lines.append('\t' + key[0].upper() + key[1:] + ' *' + typ + ' `json:"' + key + ',omitempty"`')
    lines.append('}\n')
(ROOT / 'logs/write_types_generated.go').write_text('\n'.join(lines))
subprocess.run(['gofmt', '-w', str(ROOT / 'logs/write_types_generated.go')], check=True)
